import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const revision = 'c239062ae02961df18ab7da1671d01b4388204e0';
const source = `https://raw.githubusercontent.com/wolfgarbe/SymSpell/${revision}/SymSpell/frequency_dictionary_en_82_765.txt`;
const sourceSha256 = 'c604e1121e398ae7c7fbf777f11e0a0f2fa66eda932cb9fba1321466cf3acd7b';
const bytes = process.argv[2] ? await readFile(process.argv[2]) : await (async () => {
  const response = await fetch(source, {signal: AbortSignal.timeout(30_000)});
  if (!response.ok) throw new Error(`Dictionary download failed (${response.status})`);
  return Buffer.from(await response.arrayBuffer());
})();
if (createHash('sha256').update(bytes).digest('hex') !== sourceSha256) throw new Error('Dictionary source checksum mismatch');

const entries = bytes.toString('utf8').trim().split(/\r?\n/u).map(row => {
  const [word, count] = row.split(' ');
  if (!word || !Number.isSafeInteger(Number(count)) || Number(count) <= 0) throw new Error('Invalid dictionary entry');
  return {word, count: Number(count)};
}).filter(({word}) => /^[a-z]+$/u.test(word));
// Stable frequency order doubles as a deterministic tie-breaker at runtime.
entries.sort((a, b) => b.count - a.count || (a.word < b.word ? -1 : a.word > b.word ? 1 : 0));
const output = `/*! English frequency data: Wolf Garbe / SymSpell, Google Books Ngrams (CC BY 3.0), SCOWL.\n * Attribution and source licenses: licenses/spelling/README.md.\n * Generated by scripts/generate-spelling-dictionary.mjs; do not edit. */\nexport const dictionaryWords = '${entries.map(entry => entry.word).join(' ')}';\nexport const dictionaryCounts = '${entries.slice(0, 20_000).map(entry => entry.count).join(' ')}';\n`;
await writeFile(new URL('../packages/engine/src/dictionary.generated.ts', import.meta.url), output);
await writeFile(new URL('../packages/engine/dictionary-provenance.json', import.meta.url), JSON.stringify({
  source, revision, sourceSha256, generatedSha256: createHash('sha256').update(output).digest('hex'),
  sourceEntries: 82_833, acceptedWords: entries.length, candidateWords: 20_000,
  transformation: 'ASCII lowercase words; descending frequency, lexical ties; counts retained for the top 20000.',
}, null, 2) + '\n');
console.log(`Generated ${entries.length} accepted words and 20000 ranked correction candidates.`);
